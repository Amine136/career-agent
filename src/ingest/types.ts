import type { RunStats } from "../core/repository.js";
import type { IngestBudget } from "./budget.js";
import type { CompanyGuard } from "./company-guard.js";

// Paid source first so its limited budget always completes before the free LinkedIn sweep.
export const DEFAULT_SOURCES = ["indeed", "linkedin"];

export interface IngestOptions {
  sources?: string[];
  countries?: string[];
  queries?: string[];
  pages?: number;
  now?: Date;
  signal?: AbortSignal;
  /** Absolute epoch-ms deadline shared across sources (scheduler self-limits below Cloud Run's timeout). */
  deadline?: number;
  /**
   * Shared run budget (total + per-country caps). `ingestAll` creates one and passes it to every
   * source so the per-country cap counts LinkedIn and Indeed together.
   */
  budget?: IngestBudget;
  /**
   * Shared per-company diversity guard. `ingestAll` loads the trailing-window counts once and
   * passes it to every source so LinkedIn and Indeed count inserts against the same company cap.
   */
  companyGuard?: CompanyGuard;
  /**
   * Groups the `runs` rows of one scheduler invocation (indeed + linkedin + retention) so the
   * post-run report can analyze an invocation and detect a missing one. Generated by `ingestAll`
   * when absent.
   */
  invocationId?: string;
}

export interface IngestReport {
  source: string;
  status: "success" | "partial" | "failed";
  stats: RunStats;
}
